// Embeds files the engine and CLI need at runtime as generated modules, so they work
// without file system access to this repository (the engine also runs in the browser):
// - packages/adapter-tanstack/templates → packages/adapter-tanstack/src/templates.gen.ts
// - examples/*/smithable*.yml           → packages/cli/src/starters.gen.ts
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const repo = new URL("..", import.meta.url).pathname;

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}

function writeModule(target, name, entries, source) {
  const body = entries
    .map(([key, text]) => `  ${JSON.stringify(key)}: ${JSON.stringify(text)},`)
    .join("\n");
  writeFileSync(
    join(repo, target),
    `// Generated by scripts/embed.mjs from ${source}. Do not edit.\nexport const ${name}: Record<string, string> = {\n${body}\n};\n`,
  );
  console.log(`Embedded ${entries.length} files into ${target}.`);
}

const templates = join(repo, "packages/adapter-tanstack/templates");
writeModule(
  "packages/adapter-tanstack/src/templates.gen.ts",
  "TEMPLATES",
  walk(templates)
    .sort()
    .map((file) => [relative(templates, file), readFileSync(file, "utf8")]),
  "packages/adapter-tanstack/templates",
);

const examples = join(repo, "examples");
const starters = readdirSync(examples, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort()
  .map((name) => {
    const files = readdirSync(join(examples, name))
      .filter((f) => /^smithable(\.[a-z]+)?\.yml$/.test(f))
      .sort()
      .map((f) => [
        f,
        readFileSync(join(examples, name, f), "utf8").replace(/^# yaml-language-server:.*\n/, ""),
      ]);
    return [name, Object.fromEntries(files)];
  });
// A starter's own custom code (examples/*/src/custom/**), written by `smithable new` for the
// plain starter only: an app drafted from it may have changed what the code relies on.
const code = starters.map(([name]) => {
  const dir = join(examples, name, "src", "custom");
  const files = existsSync(dir)
    ? walk(dir)
        .sort()
        .map((path) => [relative(join(examples, name), path), readFileSync(path, "utf8")])
    : [];
  return [name, Object.fromEntries(files)];
});
// A starter's pictures (examples/*/public/**), base64: every app from the starter gets them.
const assets = starters.map(([name]) => {
  const dir = join(examples, name, "public");
  const files = existsSync(dir)
    ? walk(dir)
        .sort()
        .map((path) => [
          relative(join(examples, name), path),
          readFileSync(path).toString("base64"),
        ])
    : [];
  return [name, Object.fromEntries(files)];
});
// A starter's sample records (examples/*/samples/*.yml): copied into a new project from it.
const samples = starters.map(([name]) => {
  const dir = join(examples, name, "samples");
  const files = existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => /\.ya?ml$/.test(f))
        .sort()
        .map((f) => [`samples/${f}`, readFileSync(join(dir, f), "utf8")])
    : [];
  return [name, Object.fromEntries(files)];
});
const body = starters
  .map(([name, files]) => `  ${JSON.stringify(name)}: ${JSON.stringify(files)},`)
  .join("\n");
writeFileSync(
  join(repo, "packages/cli/src/starters.gen.ts"),
  `// Generated by scripts/embed.mjs from examples/*/smithable*.yml, examples/*/src/custom, examples/*/public and examples/*/samples. Do not edit.\nexport const STARTERS: Record<string, Record<string, string>> = {\n${body}\n};\n\nexport const STARTER_CODE: Record<string, Record<string, string>> = {\n${code.map(([name, files]) => `  ${JSON.stringify(name)}: ${JSON.stringify(files)},`).join("\n")}\n};\n\n/** Pictures and other public files, base64. */\nexport const STARTER_ASSETS: Record<string, Record<string, string>> = {\n${assets.map(([name, files]) => `  ${JSON.stringify(name)}: ${JSON.stringify(files)},`).join("\n")}\n};\n\n/** Sample records (samples/<Model>.yml), for the plain starter. */\nexport const STARTER_SAMPLES: Record<string, Record<string, string>> = {\n${samples.map(([name, files]) => `  ${JSON.stringify(name)}: ${JSON.stringify(files)},`).join("\n")}\n};\n`,
);
console.log(`Embedded ${starters.length} starters into packages/cli/src/starters.gen.ts.`);
