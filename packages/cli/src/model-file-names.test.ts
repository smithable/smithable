// A model named like one of the app's own files (T1236): a model Card once wrote the same
// src/generated/card.ts as the app card, the record of written files named the other one, and
// the third change after it was refused as an edit by hand.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { expect, test } from "vitest";
import { run } from "./cli.js";
import { hashFile, readRecord } from "./generate.js";
import { git } from "./git.js";
import { tempDir } from "./test-dir.js";
import { captureIo } from "./test-io.js";

const smithable = async (args: string[]) => {
  const io = captureIo();
  expect(await run(args, io), `${args.join(" ")}\n${io.stderr}`).toBe(0);
  return io;
};

test("a model named Card, then two more changes, all go through", async () => {
  const dir = join(tempDir("smithable-model-card-"), "app");
  await smithable(["new", dir, "--starter", "records"]);
  await smithable(["op", "addModel", "Card", "title=string!", "--dir", dir]);
  await smithable([
    "op",
    "setPublic",
    "--pages",
    "home,items",
    "--read",
    "Item,Card",
    "--dir",
    dir,
  ]);
  await smithable(["op", "setText", "Hello", "pages", "home", "hero", "title", "--dir", dir]);
  // Every file the record names is the file on disk.
  for (const [path, hash] of Object.entries(readRecord(dir).files))
    expect(hashFile(join(dir, path)), path).toBe(hash);
}, 120_000);

test("a model named like a file the app itself writes is refused, and nothing changes", async () => {
  const dir = join(tempDir("smithable-model-site-"), "app");
  await smithable(["new", dir, "--starter", "records"]);
  const io = captureIo();
  expect(await run(["op", "addModel", "Site", "title=string!", "--dir", dir], io)).not.toBe(0);
  expect(io.stderr + io.stdout).toContain(
    "The model Site would write src/generated/site.ts, which the app itself uses: give the model another name.",
  );
  await smithable(["op", "setText", "Hello", "pages", "home", "hero", "title", "--dir", dir]);
}, 120_000);

/** The app card's server function as it was written to src/generated/card.ts before T1236. */
const OLD_CARD = `// Generated by Smithable from smithable.yml. Do not edit: this file is overwritten on every change.
import { createServerFn } from "@tanstack/react-start";
import { AccessDenied } from "#/kit/access";
import { currentViewer } from "#/lib/viewer.server";
import { CARDS, MAIN } from "./card.server";

/** The app card's facts, in every language: for the administrators only. */
export const appCard = createServerFn().handler(async () => {
  const viewer = await currentViewer();
  if (viewer?.role !== "admin") throw new AccessDenied(Boolean(viewer));
  return { cards: CARDS, main: MAIN };
});
`;
const OLD_CARD_SERVER = `// Generated by Smithable from smithable.yml. Do not edit: this file is overwritten on every change.
import type { CardFacts } from "#/kit/card";

export const CARDS: Record<string, CardFacts> = {};
export const MAIN = "en";
`;
const commit = (dir: string) => {
  expect(git(dir, ["add", "-A"]).ok).toBe(true);
  expect(git(dir, ["commit", "-qm", "as an older Smithable left it"]).ok).toBe(true);
};

test("an app the old clash left stuck goes on, and a real edit by hand is still refused", async () => {
  const dir = join(tempDir("smithable-model-card-old-"), "app");
  await smithable(["new", dir, "--starter", "records"]);
  await smithable(["op", "addModel", "Card", "title=string!", "--dir", dir]);
  // The app card's file on disk where the record names the model's.
  writeFileSync(join(dir, "src/generated/card.ts"), OLD_CARD);
  commit(dir);
  await smithable(["op", "setText", "Hello", "pages", "home", "hero", "title", "--dir", dir]);
  expect(readFileSync(join(dir, "src/generated/card.ts"), "utf8")).not.toBe(OLD_CARD);
  // The model's file on disk where the record names the app card's, and the change is to Card.
  const model2 = readFileSync(join(dir, "src/generated/card.ts"), "utf8");
  writeFileSync(join(dir, "src/generated/card.ts"), OLD_CARD);
  const record = readRecord(dir);
  record.files["src/generated/card.ts"] = hashFile(join(dir, "src/generated/card.ts"));
  writeFileSync(join(dir, "src/generated/card.ts"), model2);
  writeFileSync(join(dir, ".smithable/files.json"), `${JSON.stringify(record, null, 2)}\n`);
  commit(dir);
  await smithable(["op", "addField", "Card", "note", "text", "--dir", dir]);
  expect(readFileSync(join(dir, "src/generated/card.ts"), "utf8")).toContain("note");
  const model = readFileSync(join(dir, "src/generated/card.ts"), "utf8");
  // A real edit by hand.
  writeFileSync(join(dir, "src/generated/card.ts"), `${model}// mine\n`);
  commit(dir);
  const io = captureIo();
  expect(
    await run(["op", "setText", "Hey", "pages", "home", "hero", "title", "--dir", dir], io),
  ).not.toBe(0);
  expect(io.stderr + io.stdout).toContain("edited by hand");
}, 120_000);

test("an older app's card files in src/generated are removed once the card is in src/lib", async () => {
  const dir = join(tempDir("smithable-old-card-"), "app");
  await smithable(["new", dir, "--starter", "records"]);
  writeFileSync(join(dir, "src/generated/card.ts"), OLD_CARD);
  writeFileSync(join(dir, "src/generated/card.server.ts"), OLD_CARD_SERVER);
  const record = readRecord(dir);
  for (const path of ["src/generated/card.ts", "src/generated/card.server.ts"])
    record.files[path] = hashFile(join(dir, path));
  writeFileSync(join(dir, ".smithable/files.json"), `${JSON.stringify(record, null, 2)}\n`);
  commit(dir);
  await smithable(["op", "setText", "Hello", "pages", "home", "hero", "title", "--dir", dir]);
  expect(existsSync(join(dir, "src/generated/card.ts"))).toBe(false);
  expect(existsSync(join(dir, "src/generated/card.server.ts"))).toBe(false);
  expect(existsSync(join(dir, "src/lib/app-card.ts"))).toBe(true);
}, 120_000);

test("an older app's card file edited by hand is still refused", async () => {
  for (const [path, text] of [
    ["src/generated/card.ts", OLD_CARD],
    ["src/generated/card.server.ts", OLD_CARD_SERVER],
  ] as const) {
    const dir = join(tempDir("smithable-old-card-edited-"), "app");
    await smithable(["new", dir, "--starter", "records"]);
    writeFileSync(join(dir, path), text);
    const record = readRecord(dir);
    record.files[path] = hashFile(join(dir, path));
    writeFileSync(join(dir, ".smithable/files.json"), `${JSON.stringify(record, null, 2)}\n`);
    writeFileSync(join(dir, path), text.replace("MAIN", "MAIN_").concat("// mine\n"));
    commit(dir);
    const io = captureIo();
    expect(
      await run(["op", "setText", "Hey", "pages", "home", "hero", "title", "--dir", dir], io),
      path,
    ).not.toBe(0);
    expect(io.stderr + io.stdout).toContain("edited by hand");
    expect(existsSync(join(dir, path))).toBe(true);
  }
}, 180_000);
