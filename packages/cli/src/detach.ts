import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { readme } from "@smithable/adapter-tanstack";
import { git, uncommitted } from "./git.js";
import type { Io } from "./io.js";
import { loadSpec } from "./validate.js";

const GENERATED_HEADER = /^\/\/ Generated by Smithable[^\n]*\n/;
const KIT_PREFIX = /^(\/\/|\/\*) Smithable app kit: (\w)/;

/**
 * `smithable detach`: turns the project into an ordinary one (ARCHITECTURE §6.8). Removes the
 * generated-file headers and Smithable's records, keeps the spec files as documentation in
 * docs/smithable/, and rewrites the README. Custom code is left as it is.
 */
export function detach(dir: string, io: Io): number {
  const recordPath = join(dir, ".smithable", "files.json");
  if (!existsSync(recordPath)) {
    io.err(`${dir} is not a Smithable project (there is no .smithable/files.json).\n`);
    return 1;
  }
  if (git(dir, ["rev-parse", "--is-inside-work-tree"]).ok && uncommitted(dir).length > 0) {
    io.err(
      "Commit or discard your changes first, so the detach can be reviewed and reverted on its own.\n",
    );
    return 1;
  }
  const { ir } = loadSpec(dir, io);
  if (!ir) return 1;

  const { files } = JSON.parse(readFileSync(recordPath, "utf8")) as {
    files: Record<string, string>;
  };
  let cleaned = 0;
  for (const path of Object.keys(files)) {
    const file = join(dir, path);
    if (!existsSync(file)) continue;
    const text = readFileSync(file, "utf8");
    const plain = text
      .replace(GENERATED_HEADER, "")
      .replace(
        KIT_PREFIX,
        (_, comment: string, first: string) => `${comment} ${first.toUpperCase()}`,
      );
    if (plain !== text) {
      writeFileSync(file, plain);
      cleaned++;
    }
  }
  writeFileSync(join(dir, "README.md"), readme(ir, true));

  const docs = join(dir, "docs", "smithable");
  const specs = readdirSync(dir).filter((f) => /^smithable(\.[a-z]+)?\.yml$/.test(f));
  mkdirSync(docs, { recursive: true });
  for (const spec of specs) renameSync(join(dir, spec), join(docs, spec));
  for (const path of ["smithable.lock", ".smithable", join("data", ".smithable")]) {
    rmSync(join(dir, path), { recursive: true, force: true });
  }
  io.out(
    `Detached: ${cleaned} files no longer mention Smithable, the README is rewritten, and ${specs.join(", ")} ` +
      `moved to docs/smithable/ as documentation.\nThis is now an ordinary TanStack Start + Drizzle project.\n`,
  );
  return 0;
}
