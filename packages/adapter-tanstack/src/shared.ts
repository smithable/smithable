/** Visible text: from smithable.content.yml when given there, otherwise derived from names. */
export function texts(content: ContentIR) {
  return {
    modelLabel: (model: ModelIR) => content.models[model.name]?.label ?? humanize(model.name),
    modelPluralLabel: (model: ModelIR) => {
      const own = content.models[model.name];
      return own?.pluralLabel ?? (own?.label ? plural(own.label) : humanize(plural(model.name)));
    },
    field: (model: ModelIR, field: FieldIR) => content.models[model.name]?.fields[field.name] ?? {},
    /** The reservation block's words for a model with a capacity, as props: only those given. */
    reserve: (model: ModelIR) =>
      Object.entries(content.models[model.name]?.reserve ?? {})
        .map(([key, text]) => ` ${key}Label=${attr(text)}`)
        .join(""),
    pageTitle: (id: string) => content.pages[id]?.title ?? humanize(id),
    /** The subtitle prop of a page's header on its own line (indented so), or nothing. */
    pageSubtitle: (id: string, indent = 8) => {
      const subtitle = content.pages[id]?.subtitle;
      return subtitle ? `\n${" ".repeat(indent)}subtitle=${attr(subtitle)}` : "";
    },
    /** A landing section's or dashboard tile's texts. */
    section: (page: string, name: string) => content.pages[page]?.sections?.[name] ?? {},
    /** A form section's heading, from smithable.content.yml (pages.<page>.form.sections.<name>). */
    formSection: (page: string, name: string) => content.pages[page]?.formSections?.[name] ?? {},
    /** A calculator field's label and help: the page's, or a landing section's. */
    calculatorField: (page: string, field: string, section?: string) =>
      (section
        ? content.pages[page]?.sections?.[section]?.fields?.[field]
        : content.pages[page]?.fields?.[field]) ?? {},
    menuLabel: (name: string) =>
      content.menus[name]?.label ?? (name === "main" ? undefined : humanize(name)),
  };
}

export type Texts = ReturnType<typeof texts>;

/** The model's Drizzle table variable and SQL table name. */
export function tableNames(model: ModelIR) {
  const pluralName = plural(model.name);
  return { table: camel(pluralName), sqlTable: snake(pluralName) };
}

// Names derived from a model, used consistently across files.
export function names(model: ModelIR, t: Texts) {
  const pluralName = plural(model.name);
  return {
    ...tableNames(model),
    ui: `${camel(model.name)}Ui`,
    schema: `${camel(model.name)}Schema`,
    list: `list${pascal(pluralName)}`,
    get: `get${model.name}`,
    create: `create${model.name}`,
    update: `update${model.name}`,
    remove: `delete${model.name}`,
    module: `#/generated/${kebab(model.name)}`,
    options: `${camel(model.name)}Options`,
    access: `${camel(model.name)}Access`,
    data: `${camel(model.name)}Data`,
    values: `${model.name}Values`,
    label: t.modelLabel(model),
    pluralLabel: t.modelPluralLabel(model),
  };
}

/** The column holding a record's owner: the automatic owner, or the model's ownedBy field. */
export function ownerKey(model: ModelIR): string {
  return model.ownedBy ? `${model.ownedBy}Id` : "ownerId";
}

/** Records only their owners read (for some role): then "unique" means unique per owner. */
export function uniquePerOwner(model: ModelIR, auth: AuthIR): boolean {
  const read = modelAccess(model, auth).read;
  return (
    hasSignIn(auth) &&
    read.owner &&
    !read.public &&
    auth.roles.some((r) => !read.roles.includes(r.name))
  );
}

/** Fields that refer to a user, e.g. an account manager. */
export function userFields(fields: FieldIR[] | ModelIR): FieldIR[] {
  return (Array.isArray(fields) ? fields : fields.fields).filter(
    (f) => f.type.kind === "relation" && f.type.model === USER_MODEL,
  );
}

/** The model of a crud page; only crud pages have a list to customize. */
export function crudModel(ir: SpecIR, page: PageIR): ModelIR {
  const model = pageModel(page);
  if (!model)
    throw new Error(`Page ${page.id} is a ${page.pattern.kind} page, not a list of records.`);
  return modelNamed(ir, model);
}

export function modelNamed(ir: SpecIR, name: string): ModelIR {
  const model = ir.models.find((m) => m.name === name);
  if (!model) throw new Error(`Unknown model ${name}`);
  return model;
}

/** Fields stored on the model itself: not lists of related records, not computed fields. */
export function storedFields(model: ModelIR): FieldIR[] {
  return model.fields.filter((f) => !(f.type.kind === "relation" && f.type.many) && !f.formula);
}

/** Fields a person sees for a record: stored and computed ones. */
export function shownFields(model: ModelIR): FieldIR[] {
  return model.fields.filter((f) => !(f.type.kind === "relation" && f.type.many));
}

/** The references a model holds, e.g. Order.customer. */
export function references(
  model: ModelIR,
): (FieldIR & { type: { kind: "relation"; model: string } })[] {
  return model.fields.filter(
    (f): f is FieldIR & { type: { kind: "relation"; model: string; many: false } } =>
      f.type.kind === "relation" && !f.type.many && f.type.model !== USER_MODEL,
  );
}

/** The lists of related records a model shows, e.g. Customer.orders. */
export function lists(model: ModelIR): (FieldIR & { type: { kind: "relation"; model: string } })[] {
  return model.fields.filter(
    (f): f is FieldIR & { type: { kind: "relation"; model: string; many: true } } =>
      f.type.kind === "relation" && f.type.many,
  );
}

/** The data key of a stored field: references are stored as <name>Id. */
export function dataKey(field: FieldIR): string {
  return field.type.kind === "relation" ? `${field.name}Id` : field.name;
}

/** A field's column key by the field's name in the spec (the spec has already checked it). */
export function keyOf(model: ModelIR, name: string): string {
  return dataKey(model.fields.find((f) => f.name === name) as FieldIR);
}

/**
 * A crud page's routes drawn inside a data page (an admin view of every model): the list's
 * heading is the model's, its links stay inside the page, and its list shows the newest
 * `LIMIT` records. Absent for ordinary crud pages, whose files do not change.
 */
export interface Within {
  /** The data page's route, e.g. /admin. */
  base: string;
  /** The models the data page shows. */
  models: string[];
}

/** How many records a data page's list shows: the newest; a note says when there are more. */
export const DATA_LIMIT = 500;

/** Where a model's records live inside a data page, e.g. /admin/order-lines. */
export function dataRoute(within: Within, model: string): string {
  return join(within.base, kebab(plural(model)));
}

/** Text placed deeper in generated code: every line after the first gets `spaces` more. */
export function indent(text: string, spaces: number): string {
  return text.split("\n").join(`\n${" ".repeat(spaces)}`);
}

/** The field that names a related record; users are named by their name. */
export function relatedTitle(ir: SpecIR, model: string): string {
  return model === USER_MODEL ? "name" : titleField(modelNamed(ir, model));
}

