/**
 * A text as a JSX attribute's value: a plain one as a string, as always; one with quotes, a
 * backslash or a line break in braces, since an attribute string keeps escapes as written.
 */
export function attr(value: string): string {
  const json = JSON.stringify(value);
  return json.includes("\\") ? `{${json}}` : json;
}

/** Import lines collected per module, merged and in first-use order. */
export function importList() {
  const modules = new Map<string, Set<string>>();
  return {
    add(module: string, ...names: string[]) {
      const set = modules.get(module) ?? new Set<string>();
      for (const name of names) set.add(name);
      modules.set(module, set);
      return this;
    },
    /** A namespace import ("* as schema") gets a line of its own. */
    render(): string {
      return [...modules]
        .map(([m, all]) => {
          const spaces = [...all].filter((name) => name.startsWith("* as "));
          const named = [...all].filter((name) => !name.startsWith("* as "));
          return [
            ...spaces.map((name) => `import ${name} from "${m}";\n`),
            ...(named.length ? [`import { ${named.join(", ")} } from "${m}";\n`] : []),
          ].join("");
        })
        .join("");
    },
    names(): Set<string> {
      return new Set([...modules.values()].flatMap((names) => [...names]));
    },
    /** Adds another list's imports, e.g. to put a route and its component in one file. */
    merge(other: { entries(): [string, Set<string>][] }) {
      for (const [module, names] of other.entries()) this.add(module, ...names);
      return this;
    },
    entries(): [string, Set<string>][] {
      return [...modules];
    },
  };
}

/** The first page of the app itself: not a landing or onboarding page. */
export function appStart(ir: SpecIR): PageIR | undefined {
  const inApp = (p: PageIR | undefined) =>
    p && p.pattern.kind !== "landing" && p.pattern.kind !== "onboarding";
  return (
    ir.navigation
      .flatMap((m) => m.pages)
      .map((id) => ir.pages.find((p) => p.id === id))
      .find(inApp) ?? ir.pages.find(inApp)
  );
}

/**
 * The props of a page's form from smithable.ux.yml, or nothing: the field order, the sections
 * (with their headings from smithable.content.yml), the columns and the controls.
 */
export function fieldOrder(page: PageIR, model: ModelIR, ux: UxIR, t?: Texts): string {
  const own = ux.pages[page.id];
  if (!own) return "";
  const key = (name: string) => keyOf(model, name);
  const props: string[] = [];
  if (own.fieldOrder) props.push(`fieldOrder={${literal(own.fieldOrder.map(key))}}`);
  if (own.sections?.length)
    props.push(
      `sections={${literal(
        own.sections.map((s) => ({
          name: s.name,
          title: t?.formSection(page.id, s.name).title ?? humanize(s.name),
          fields: s.fields.map(key),
        })),
      )}}`,
    );
  if (own.formColumns === 2) props.push("formColumns={2}");
  if (own.control && Object.keys(own.control).length)
    props.push(
      `control={${literal(Object.fromEntries(Object.entries(own.control).map(([f, c]) => [key(f), c])))}}`,
    );
  return props.map((p) => `\n        ${p}`).join("");
}

/** Whether a form needs choices loaded: for references to records or users. */
export function hasChoices(model: ModelIR): boolean {
  return references(model).length + userFields(model).length > 0;
}

/** Loader code for the choices of a model's references, e.g. { customerId: await customerOptions() }. */
export function optionsFor(
  model: ModelIR,
  t: Texts,
  ir: SpecIR,
): { imports: string[]; expr: string } {
  const refs = references(model);
  const modules = new Map<string, string[]>();
  for (const ref of refs) {
    const target = names(modelNamed(ir, ref.type.model), t);
    const list = modules.get(target.module) ?? [];
    if (!list.includes(target.options)) list.push(target.options);
    modules.set(target.module, list);
  }
  const entries = refs.map(
    (ref) => `${dataKey(ref)}: await ${names(modelNamed(ir, ref.type.model), t).options}()`,
  );
  // Whose record it is (ownedBy): chosen only by a role that may change everyone's.
  const users = userFields(model).filter((f) => f.name !== model.ownedBy);
  if (users.length) modules.set("#/generated/users", ["userOptions"]);
  for (const f of users) entries.push(`${dataKey(f)}: await userOptions()`);
  const owner = model.ownedBy && userFields(model).find((f) => f.name === model.ownedBy);
  if (owner) {
    const n = names(model, t);
    modules.set(n.module, [...(modules.get(n.module) ?? []), n.ownerOptions]);
    entries.push(`${dataKey(owner)}: await ${n.ownerOptions}()`);
  }
  return {
    imports: [...modules].map(([module, fns]) => `import { ${fns.join(", ")} } from "${module}";`),
    expr: `{ ${entries.join(", ")} }`,
  };
}

export function indexPath(route: string): string {
  return route === "/" ? "/" : `${route}/`;
}

export function join(route: string, segment: string): string {
  return route === "/" ? `/${segment}` : `${route}/${segment}`;
}

/** A TypeScript literal for plain data, formatted like Biome would. */
/** Code written as is inside a literal (a function, a reference), not as data. */
class Code {
  constructor(readonly text: string) {}
}
export const code = (text: string) => new Code(text);

/**
 * A value read each time it is asked for, written as a getter: a text in the language now
 * (languages.md §4), `get label() { return tx("Customer"); }`.
 */
export class Getter {
  constructor(readonly text: string) {}
}

export function literal(value: unknown, indent = ""): string {
  if (value instanceof Code) return value.text;
  if (Array.isArray(value)) {
    const inline = `[${value.map((v) => literal(v)).join(", ")}]`;
    if (inline.length <= 80 && !inline.includes("\n")) return inline;
    const inner = `${indent}  `;
    return `[\n${value.map((v) => `${inner}${literal(v, inner)},`).join("\n")}\n${indent}]`;
  }
  if (value !== null && typeof value === "object") {
    const entries = Object.entries(value).filter(([, v]) => v !== undefined);
    const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
    const entry = (k: string, v: unknown, inner = "") =>
      v instanceof Getter
        ? `get ${key(k)}() { return ${v.text}; }`
        : `${key(k)}: ${literal(v, inner)}`;
    const inline = `{ ${entries.map(([k, v]) => entry(k, v)).join(", ")} }`;
    if (inline.length <= 80 && !inline.includes("\n")) return inline;
    const inner = `${indent}  `;
    return `{\n${entries.map(([k, v]) => `${inner}${entry(k, v, inner)},`).join("\n")}\n${indent}}`;
  }
  return JSON.stringify(value);
}

/** Whether a model's records can be marked as favorites (a crud page says so; marks need sign-in). */
export function hasFavorites(model: ModelIR, ir: SpecIR, auth: AuthIR): boolean {
  return (
    hasSignIn(auth) &&
    ir.pages.some((p) => p.pattern.kind === "crud" && p.pattern.model === model.name && p.favorites)
  );
}

/** The standard actions a page offers (docs/design/actions.md): on its records' pages. */
export function standardActions(page: PageIR, ir: SpecIR): StandardActionIR[] {
  return (page.actions ?? []).flatMap((name) =>
    ir.actions.filter(
      (a): a is StandardActionIR => a.name === name && !a.custom && !a.merge && !a.split,
    ),
  );
}

/** The splits a page offers (docs/design/intents.md §4): "Split…" on its records' pages. */
export function splitActions(page: PageIR, ir: SpecIR): StandardActionIR[] {
  return (page.actions ?? []).flatMap((name) =>
    ir.actions.filter(
      (a): a is StandardActionIR => a.name === name && !a.custom && a.split !== undefined,
    ),
  );
}

/** The merges a page offers (docs/design/intents.md §3): two picked in its list, or "Merge into…". */
export function mergeActions(page: PageIR, ir: SpecIR): StandardActionIR[] {
  return (page.actions ?? []).flatMap((name) =>
    ir.actions.filter(
      (a): a is StandardActionIR => a.name === name && !a.custom && a.merge !== undefined,
    ),
  );
}

/**
 * A new record's numbers counting up (`sequence: true`, orders.md §4), as entries of its insert:
 * each from its counter through the kit's nextInSequence, in the change's transaction (`tx`), kept
 * ahead of the records' highest; one counter per owner where unique fields are per owner, `owner`
 * being the code of the record's owner. The module needs `max` (and `eq` per owner) from
 * drizzle-orm and nextInSequence from the kit when the list is not empty.
 */
export function sequenceEntries(
  model: ModelIR,
  auth: AuthIR,
  table: string,
  owner: string,
): string[] {
  return model.fields
    .filter((f) => f.sequence)
    .map((f) => {
      // The counter's scope is the field's uniqueness scope (docs/design/uniqueness.md).
      const perOwner = uniqueScope(f.unique || true, model, auth) === "owner";
      const key = perOwner
        ? `\`${model.name}.${f.name}:\${${owner}}\``
        : JSON.stringify(`${model.name}.${f.name}`);
      const top = `tx.select({ n: max(${table}.${dataKey(f)}) }).from(${table})${perOwner ? `.where(eq(${table}.${ownerKey(model)}, ${owner}))` : ""}.get()?.n ?? 0`;
      return `${dataKey(f)}: nextInSequence(tx, ${key}, ${top})`;
    });
}
