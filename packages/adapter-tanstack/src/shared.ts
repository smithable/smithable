/** Where a model's records live inside a data page, e.g. /admin/order-lines. */
export function dataRoute(within: Within, model: string): string {
  return join(within.base, kebab(plural(model)));
}

/** Text placed deeper in generated code: every line after the first gets `spaces` more. */
export function indent(text: string, spaces: number): string {
  return text.split("\n").join(`\n${" ".repeat(spaces)}`);
}

/**
 * Whether a model is named by a long text (it has no short one: a message, by its words): its
 * title is then shown cut to its first line by the kit's titleOf, the API keeping the whole value.
 */
export function longTitle(model: ModelIR): boolean {
  const f = model.fields.find((x) => x.name === titleField(model));
  return f?.type.kind === "scalar" && (f.type.name === "text" || f.type.name === "markdown");
}

/** A record's title as generated code shows it: a long one cut by the kit's titleOf. */
export function shownTitle(model: ModelIR, expr: string): string {
  return longTitle(model) ? `titleOf(${expr})` : `String(${expr})`;
}

/** The field that names a related record; users are named by their name. */
export function relatedTitle(ir: SpecIR, model: string): string {
  return model === USER_MODEL ? "name" : titleField(modelNamed(ir, model));
}

/**
 * The key the kit reads a record's name under: its title field, or for a name made of parts
 * (docs/design/record-names.md) "$name", which the data functions set on the rows they return.
 */
export function shownTitleKey(ir: SpecIR, model: string): string {
  if (model === USER_MODEL) return "name";
  const m = modelNamed(ir, model);
  return composedName(m) ? "$name" : titleField(m);
}

/** Whether a model's name is made of parts, not one stored text field (today's title column). */
export function composedName(model: ModelIR): boolean {
  const parts = model.nameParts;
  if (!parts?.length) return false;
  if (parts.length > 1 || parts[0]?.through) return true;
  const f = model.fields.find((x) => x.name === parts[0]?.field);
  return !(f?.type.kind === "scalar" && ["string", "text", "markdown"].includes(f.type.name));
}

