/**
 * Who owns a file (ARCHITECTURE §6.4). "scaffold" files are created once and then belong
 * to the project and its tools, e.g. pnpm adds supply-chain exceptions to pnpm-workspace.yaml.
 */
export type Zone = "generated" | "kit" | "scaffold" | "custom";

export interface GeneratedFile {
  path: string;
  content: string;
  zone: Zone;
}

/** What every generator gets: the IR, its texts, sign-in, presentation and the options. */
export interface GenContext {
  ir: SpecIR;
  t: Texts;
  auth: AuthIR;
  ux: UxIR;
  options: GenerateOptions;
}

/**
 * The files one part of the spec generates (ARCHITECTURE §5.1), like a section registers its
 * schema and operations: generateApp runs each and adds app-wide files around them.
 */
export interface SectionGenerator {
  key: string;
  /** Kit files only apps that use this part need (sign-in, a page pattern), and whether this one does. */
  kit?: { files: string[]; used(ctx: GenContext): boolean }[];
  files(ctx: GenContext): GeneratedFile[];
}

export interface GenerateOptions {
  /** The Smithable version recorded in smithable.lock. */
  smithableVersion: string;
  /** Visible text from smithable.content.yml; anything missing is derived from names. */
  content?: ContentIR;
  auth: AuthIR;
  /** Pages with a custom component in src/custom/pages/ (found by the host). */
  customPages?: string[];
  /** Presentation from smithable.ux.yml: theme, table columns, form field order. */
  ux?: UxIR;
  /** The project's own themes (themes/<name>.yml), which the ux file's preset may name. */
  themes?: ThemeIR[];
  /** Project plugins: their extra files (ARCHITECTURE §5.1). */
  plugins?: SpecPlugin[];
  /** Libraries for custom code, from smithable.context.yml: name → exact version. */
  packages?: Record<string, string>;
  /** The project's sample records (samples/<Model>.yml), seeded instead of generated ones. */
  samples?: SamplesIR;
}

