// Browser push in a generated app (docs/design/notifications.md §4): the service worker that shows
// a push, the web app manifest (an iPhone shows pushes only for an app on its home screen), and
// the server functions the Notifications part under the person's name calls.
import { type AuthIR, humanize, type SpecIR } from "@smithable/core";
import { pushEntries } from "./outgoing.js";
import { HEADER, literal } from "./shared.js";

/** The service worker: shows a push and opens its link, the app's own pages only. */
export const SERVICE_WORKER = `// Generated by Smithable: the app's service worker for browser push (notifications.md §4).
// It shows a push (the title line) and, on a click, opens its link: the app's own pages only.
self.addEventListener("push", (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch {}
  event.waitUntil(
    self.registration.showNotification(String(data.title || ""), {
      data: { link: String(data.link || "/") },
      icon: "/favicon.svg",
    }),
  );
});
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const link = new URL(event.notification.data?.link || "/", self.location.origin);
  if (link.origin !== self.location.origin) return;
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((open) => {
      const tab = open.find((c) => c.url.startsWith(self.location.origin));
      if (tab) return tab.navigate(link.href).then((c) => (c || tab).focus());
      return self.clients.openWindow(link.href);
    }),
  );
});
`;

/** The web app manifest: the app's name and icon, opened as an app of its own. */
export function manifest(ir: SpecIR): string {
  return `${JSON.stringify(
    {
      name: ir.app.name,
      short_name: ir.app.name.slice(0, 12),
      start_url: "/",
      display: "standalone",
      icons: [{ src: "/favicon.svg", sizes: "any", type: "image/svg+xml" }],
    },
    null,
    2,
  )}\n`;
}

/**
 * The server functions of the Notifications part: which entries this person may turn on (an
 * entry for a role, to that role's people; any other to everyone signed in), which are on, and
 * turning one on or off with this browser's subscription.
 */
export function pushModule(ir: SpecIR, auth: AuthIR): string {
  const entries = pushEntries(ir, auth).map((o) => ({
    entry: o.name,
    label: humanize(o.name),
    ...(o.recipient?.kind === "role" ? { role: o.recipient.role } : {}),
  }));
  return `${HEADER}// Browser push (notifications.md §4): what the Notifications part under the person's name calls.
import { createServerFn } from "@tanstack/react-start";
import { getRequestHeaders } from "@tanstack/react-start/server";
import { z } from "zod";
import { AccessDenied, type Viewer } from "#/kit/access";
import { writeAllowed } from "#/kit/limit";
import { currentViewer } from "#/lib/viewer.server";

/** The entries that push, and the role an entry for a role reaches. */
const ENTRIES: { entry: string; label: string; role?: string }[] = ${literal(entries)};

/** The entries this person may turn on. */
const offered = (viewer: Viewer) => ENTRIES.filter((e) => !e.role || e.role === viewer.role);

async function signedIn() {
  const viewer = await currentViewer();
  if (!viewer) throw new AccessDenied(false);
  return viewer;
}

/** The person's notifications: each entry offered, whether it is on, and the key to subscribe with. */
export const pushNotifications = createServerFn().handler(async () => {
  const { pushChoices } = await import("#/kit/push.server");
  const viewer = await signedIn();
  const mine = offered(viewer);
  const { publicKey, on } = pushChoices(viewer, mine.map((e) => e.entry));
  return { publicKey, entries: mine.map(({ entry, label }) => ({ entry, label, on: on.includes(entry) })) };
});

const browser = z.object({
  endpoint: z.string().url().max(2000),
  p256dh: z.string().max(200),
  auth: z.string().max(100),
});

/** Turns one on or off, with this browser's subscription. */
export const setPushNotification = createServerFn({ method: "POST" })
  .validator(z.object({ entry: z.string(), on: z.boolean(), browser: browser.optional() }))
  .handler(async ({ data }) => {
    const { setPushChoice } = await import("#/kit/push.server");
    const viewer = await signedIn();
    writeAllowed(viewer, getRequestHeaders());
    return setPushChoice(viewer, offered(viewer).map((e) => e.entry), data.entry, data.on, data.browser);
  });

/** This browser stops getting pushes: signing out here. */
export const forgetPushBrowser = createServerFn({ method: "POST" })
  .validator(z.object({ endpoint: z.string().max(2000) }))
  .handler(async ({ data }) => {
    const { dropPushBrowser } = await import("#/kit/push.server");
    const viewer = await currentViewer();
    if (viewer) dropPushBrowser(viewer, data.endpoint);
  });
`;
}
