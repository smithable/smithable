import {
  type ContentIR,
  emptyContent,
  type FieldIR,
  type ModelIR,
  type PageIR,
  type SpecIR,
} from "@smithable/core";
import { camel, humanize, kebab, pascal, plural, snake } from "./naming.js";
import { sampleRows } from "./sample-data.js";
import { STACK_PROFILE } from "./stack.js";
import { TEMPLATES } from "./templates.gen.js";

/**
 * Who owns a file (ARCHITECTURE §6.4). "scaffold" files are created once and then belong
 * to the project and its tools, e.g. pnpm adds supply-chain exceptions to pnpm-workspace.yaml.
 */
export type Zone = "generated" | "kit" | "scaffold";

const SCAFFOLD = new Set(["pnpm-workspace.yaml", ".gitignore", ".dockerignore"]);

export interface GeneratedFile {
  path: string;
  content: string;
  zone: Zone;
}

export interface GenerateOptions {
  /** The Smithable version recorded in smithable.lock. */
  smithableVersion: string;
  /** Visible text from smithable.content.yml; anything missing is derived from names. */
  content?: ContentIR;
}

const HEADER =
  "// Generated by Smithable from smithable.yml. Do not edit: this file is overwritten on every change.\n";

/** Generates a complete TanStack Start app from the IR. Pure and deterministic. */
export function generateApp(ir: SpecIR, options: GenerateOptions): GeneratedFile[] {
  const t = texts(options.content ?? emptyContent());
  const files: GeneratedFile[] = Object.entries(TEMPLATES).map(([path, content]) => ({
    path,
    content,
    zone: SCAFFOLD.has(path) ? "scaffold" : "kit",
  }));
  const add = (path: string, content: string) => files.push({ path, content, zone: "generated" });

  add("package.json", packageJson(ir));
  add("smithable.lock", smithableLock(ir, options));
  add("README.md", readme(ir));
  add("src/generated/app.ts", appModule(ir));
  add("src/db/schema.ts", schemaModule(ir));
  add("src/db/seed.ts", seedModule(ir));
  add("src/routes/__root.tsx", rootRoute(ir, t));
  if (!ir.pages.some((p) => p.route === "/")) add("src/routes/index.tsx", indexRoute(ir));
  for (const model of ir.models)
    add(`src/generated/${kebab(model.name)}.ts`, modelModule(model, t));
  for (const page of ir.pages) {
    const model = ir.models.find((m) => m.name === page.pattern.model);
    if (!model) continue;
    const dir = page.route === "/" ? "src/routes" : `src/routes${page.route}`;
    add(`${dir}/index.tsx`, listRoute(page, model, t));
    add(`${dir}/new.tsx`, newRoute(page, model, t));
    add(`${dir}/$id.tsx`, detailRoute(page, model, t));
  }
  return files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

/** Visible text: from smithable.content.yml when given there, otherwise derived from names. */
function texts(content: ContentIR) {
  return {
    modelLabel: (model: ModelIR) => content.models[model.name]?.label ?? humanize(model.name),
    modelPluralLabel: (model: ModelIR) => {
      const own = content.models[model.name];
      return own?.pluralLabel ?? (own?.label ? plural(own.label) : humanize(plural(model.name)));
    },
    field: (model: ModelIR, field: FieldIR) => content.models[model.name]?.fields[field.name] ?? {},
    pageTitle: (id: string) => content.pages[id]?.title ?? humanize(id),
    menuLabel: (name: string) =>
      content.menus[name]?.label ?? (name === "main" ? undefined : humanize(name)),
  };
}

type Texts = ReturnType<typeof texts>;

/** The model's Drizzle table variable and SQL table name. */
function tableNames(model: ModelIR) {
  const pluralName = plural(model.name);
  return { table: camel(pluralName), sqlTable: snake(pluralName) };
}

// Names derived from a model, used consistently across files.
function names(model: ModelIR, t: Texts) {
  const pluralName = plural(model.name);
  return {
    ...tableNames(model),
    ui: `${camel(model.name)}Ui`,
    schema: `${camel(model.name)}Schema`,
    list: `list${pascal(pluralName)}`,
    get: `get${model.name}`,
    create: `create${model.name}`,
    update: `update${model.name}`,
    remove: `delete${model.name}`,
    module: `#/generated/${kebab(model.name)}`,
    label: t.modelLabel(model),
    pluralLabel: t.modelPluralLabel(model),
  };
}

function packageJson(ir: SpecIR): string {
  const pkg = {
    name: kebab(ir.app.name.replace(/[^A-Za-z0-9 -]/g, "")) || "app",
    private: true,
    type: "module",
    packageManager: STACK_PROFILE.packageManager,
    imports: { "#/*": "./src/*" },
    scripts: {
      dev: "vite dev --port 3000",
      build: "vite build",
      start: "srvx --prod -s ../client dist/server/server.js",
      typecheck: "tsc",
      routes: "tsr generate",
      "db:generate": "drizzle-kit generate",
      "db:seed": "tsx src/db/seed.ts",
      "db:studio": "drizzle-kit studio",
    },
    dependencies: STACK_PROFILE.dependencies,
    devDependencies: STACK_PROFILE.devDependencies,
  };
  return `${JSON.stringify(pkg, null, 2)}\n`;
}

function smithableLock(ir: SpecIR, options: GenerateOptions): string {
  const lock = {
    smithable: options.smithableVersion,
    spec: ir.specVersion,
    adapter: "tanstack",
    stackProfile: STACK_PROFILE.id,
  };
  return `${JSON.stringify(lock, null, 2)}\n`;
}

function appModule(ir: SpecIR): string {
  const app = {
    name: ir.app.name,
    currency: ir.app.currency ?? "EUR",
    ...(ir.app.timezone ? { timeZone: ir.app.timezone } : {}),
  };
  return `${HEADER}import type { AppUi } from "#/kit/model";

export const app: AppUi = ${literal(app)};
`;
}

// ── Database ─────────────────────────────────────────────────────────────────

function schemaModule(ir: SpecIR): string {
  const imports = new Set(["integer", "sqliteTable"]);
  const tables = ir.models.map((model) => {
    const n = tableNames(model);
    const columns = model.fields.map((field) => {
      const { expr, uses } = column(field);
      imports.add(uses);
      return `  ${field.name}: ${expr},`;
    });
    return `export const ${n.table} = sqliteTable(${JSON.stringify(n.sqlTable)}, {
  id: integer().primaryKey({ autoIncrement: true }),
${columns.join("\n")}
  createdAt: integer({ mode: "timestamp_ms" }).notNull().$defaultFn(() => new Date()),
  updatedAt: integer({ mode: "timestamp_ms" })
    .notNull()
    .$defaultFn(() => new Date())
    .$onUpdate(() => new Date()),
});`;
  });
  return `${HEADER}import { ${[...imports].sort().join(", ")} } from "drizzle-orm/sqlite-core";

${tables.join("\n\n")}
`;
}

function column(field: FieldIR): { expr: string; uses: string } {
  let expr: string;
  let uses = "text";
  if (field.type.kind === "choice") {
    expr = `text({ enum: ${literal(field.type.values)} })`;
  } else {
    switch (field.type.name) {
      case "int":
      case "money":
        uses = "integer";
        expr = "integer()";
        break;
      case "decimal":
        uses = "real";
        expr = "real()";
        break;
      case "bool":
        uses = "integer";
        expr = `integer({ mode: "boolean" })`;
        break;
      case "datetime":
        uses = "integer";
        expr = `integer({ mode: "timestamp_ms" })`;
        break;
      default:
        expr = "text()";
    }
  }
  if (field.required) expr += ".notNull()";
  if (field.unique) expr += ".unique()";
  if (field.default !== undefined) {
    if (field.type.kind === "scalar" && field.type.name === "datetime") {
      expr += `.$defaultFn(() => new Date(${JSON.stringify(field.default)}))`;
    } else if (field.type.kind === "scalar" && field.type.name === "money") {
      expr += `.default(${Math.round(Number(field.default) * 100)})`;
    } else {
      expr += `.default(${JSON.stringify(field.default)})`;
    }
  }
  return { expr, uses };
}

function seedModule(ir: SpecIR): string {
  const tables = ir.models.map((m) => tableNames(m).table);
  const blocks = ir.models.map((model) => {
    const n = tableNames(model);
    const rows = sampleRows(model).map((row) => {
      const entries = model.fields.map(
        (field) => `${field.name}: ${sampleLiteral(field, row[field.name])}`,
      );
      return `    { ${entries.join(", ")} },`;
    });
    return `if (db.select().from(${n.table}).limit(1).all().length === 0) {
  db.insert(${n.table})
    .values([
${rows.join("\n")}
    ])
    .run();
}`;
  });
  return `${HEADER}// Sample data for development. Run with \`pnpm db:seed\`; tables that already have rows are left alone.
import { db } from "./index";
${tables.length ? `import { ${tables.join(", ")} } from "./schema";\n` : ""}
${blocks.join("\n\n")}
`;
}

function sampleLiteral(field: FieldIR, value: unknown): string {
  if (value === null || value === undefined) return "null";
  if (field.type.kind === "scalar" && field.type.name === "datetime")
    return `new Date(${JSON.stringify(value)})`;
  return JSON.stringify(value);
}

// ── Models: UI description, validation and server functions ─────────────────

function modelModule(model: ModelIR, t: Texts): string {
  const n = names(model, t);
  const ui = {
    label: n.label,
    pluralLabel: n.pluralLabel,
    titleField: titleField(model),
    columns: model.fields
      .filter((f) => !(f.type.kind === "scalar" && f.type.name === "text"))
      .slice(0, 5)
      .map((f) => f.name),
    fields: model.fields.map((field) => fieldUi(model, field, t)),
  };
  const refinements = model.fields.flatMap((f) => {
    const r = refinement(f);
    return r ? [`  ${f.name}: ${r},`] : [];
  });
  const schema = refinements.length
    ? `createInsertSchema(${n.table}, {\n${refinements.join("\n")}\n})`
    : `createInsertSchema(${n.table})`;
  return `${HEADER}import { createServerFn } from "@tanstack/react-start";
import { desc, eq } from "drizzle-orm";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod";
import { db } from "#/db";
import { ${n.table} } from "#/db/schema";
import type { ModelUi } from "#/kit/model";

export const ${n.ui}: ModelUi = ${literal(ui)};

export const ${n.schema} = ${schema}.omit({ id: true, createdAt: true, updatedAt: true });

export const ${n.list} = createServerFn().handler(() =>
  db.select().from(${n.table}).orderBy(desc(${n.table}.id)).all(),
);

export const ${n.get} = createServerFn()
  .validator(z.number().int())
  .handler(({ data: id }) => db.select().from(${n.table}).where(eq(${n.table}.id, id)).get() ?? null);

export const ${n.create} = createServerFn({ method: "POST" })
  .validator(${n.schema})
  .handler(({ data }) => db.insert(${n.table}).values(data).returning().get());

export const ${n.update} = createServerFn({ method: "POST" })
  .validator(z.object({ id: z.number().int(), values: ${n.schema} }))
  .handler(({ data }) =>
    db.update(${n.table}).set(data.values).where(eq(${n.table}.id, data.id)).returning().get(),
  );

export const ${n.remove} = createServerFn({ method: "POST" })
  .validator(z.number().int())
  .handler(({ data: id }) => {
    db.delete(${n.table}).where(eq(${n.table}.id, id)).run();
  });
`;
}

function fieldUi(model: ModelIR, field: FieldIR, t: Texts) {
  const kind = field.type.kind === "choice" ? "choice" : field.type.name;
  const own = t.field(model, field);
  return {
    name: field.name,
    label: own.label ?? humanize(field.name),
    kind,
    required: field.required,
    ...(own.help ? { help: own.help } : {}),
    ...(field.type.kind === "choice"
      ? {
          choices: field.type.values.map((value) => ({
            value,
            label: own.values?.[value] ?? humanize(value),
          })),
        }
      : {}),
    ...(field.default !== undefined
      ? { default: kind === "money" ? Math.round(Number(field.default) * 100) : field.default }
      : {}),
  };
}

function titleField(model: ModelIR): string {
  const strings = model.fields.filter((f) => f.type.kind === "scalar" && f.type.name === "string");
  return (strings.find((f) => /name|title/i.test(f.name)) ?? strings[0])?.name ?? "id";
}

/** Zod refinements that go beyond the column types: formats, required text, bounds. */
function refinement(field: FieldIR): string | undefined {
  const optional = field.required ? "" : ".nullish()";
  if (field.type.kind === "choice") return undefined;
  const bounds = (scale: number) =>
    `${field.min !== undefined ? `.min(${field.min * scale})` : ""}${field.max !== undefined ? `.max(${field.max * scale})` : ""}`;
  switch (field.type.name) {
    case "email":
      return `z.email("Enter a valid email address")${optional}`;
    case "url":
      return `z.url("Enter a valid web address")${optional}`;
    case "phone":
      return `(s) => s.regex(/^\\+?[0-9 ()-]{5,20}$/, "Enter a valid phone number")`;
    case "date":
      return `(s) => s.regex(/^\\d{4}-\\d{2}-\\d{2}$/, "Enter a valid date")`;
    case "string":
    case "text":
      return field.required ? `(s) => s.trim().min(1, "Required")` : undefined;
    case "int":
    case "decimal":
      return bounds(1) ? `(s) => s${bounds(1)}` : undefined;
    case "money":
      return bounds(100) ? `(s) => s${bounds(100)}` : undefined;
    default:
      return undefined;
  }
}

// ── Routes ───────────────────────────────────────────────────────────────────

function rootRoute(ir: SpecIR, t: Texts): string {
  const pageRoute = new Map(ir.pages.map((p) => [p.id, p.route]));
  const menus = ir.navigation.map((menu) => {
    const items = menu.pages.map(
      (id) =>
        `      { to: ${JSON.stringify(pageRoute.get(id) ?? "/")}, label: ${JSON.stringify(t.pageTitle(id))} },`,
    );
    const menuLabel = t.menuLabel(menu.name);
    const label = menuLabel === undefined ? "" : ` label: ${JSON.stringify(menuLabel)},`;
    return `  {\n    name: ${JSON.stringify(menu.name)},${label}\n    items: [\n${items.join("\n")}\n    ],\n  },`;
  });
  return `${HEADER}import { createRootRoute, HeadContent, Scripts } from "@tanstack/react-router";
import { app } from "#/generated/app";
import { AppShell, type MenuUi } from "#/kit/AppShell";
import appCss from "#/styles.css?url";

const menus: MenuUi[] = [
${menus.join("\n")}
];

export const Route = createRootRoute({
  head: () => ({
    meta: [
      { charSet: "utf-8" },
      { name: "viewport", content: "width=device-width, initial-scale=1" },
      { title: app.name },
    ],
    links: [{ rel: "stylesheet", href: appCss }],
  }),
  shellComponent: RootDocument,
});

function RootDocument({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        <AppShell appName={app.name} menus={menus}>
          {children}
        </AppShell>
        <Scripts />
      </body>
    </html>
  );
}
`;
}

function indexRoute(ir: SpecIR): string {
  const first = ir.navigation[0]?.pages[0] ?? ir.pages[0]?.id;
  const target = ir.pages.find((p) => p.id === first);
  if (!target) {
    return `${HEADER}import { createFileRoute } from "@tanstack/react-router";
import { PageHeader } from "#/kit/AppShell";

export const Route = createFileRoute("/")({ component: HomePage });

function HomePage() {
  return <PageHeader title="Welcome" />;
}
`;
  }
  return `${HEADER}import { createFileRoute, redirect } from "@tanstack/react-router";

export const Route = createFileRoute("/")({
  beforeLoad: () => {
    throw redirect({ to: ${JSON.stringify(target.route)} });
  },
});
`;
}

function listRoute(page: PageIR, model: ModelIR, t: Texts): string {
  const n = names(model, t);
  const component = `${pascal(page.id)}Page`;
  return `${HEADER}import { createFileRoute, Link, useNavigate } from "@tanstack/react-router";
import { buttonVariants } from "#/components/ui/button";
import { app } from "#/generated/app";
import { ${n.list}, ${n.ui} } from "${n.module}";
import { PageHeader } from "#/kit/AppShell";
import { ModelTable } from "#/kit/ModelTable";

export const Route = createFileRoute(${JSON.stringify(indexPath(page.route))})({
  loader: () => ${n.list}(),
  component: ${component},
});

function ${component}() {
  const rows = Route.useLoaderData();
  const navigate = useNavigate();
  const newButton = (
    <Link to=${JSON.stringify(join(page.route, "new"))} className={buttonVariants()}>
      New ${n.label.toLowerCase()}
    </Link>
  );
  return (
    <>
      <PageHeader title=${JSON.stringify(t.pageTitle(page.id))} actions={newButton} />
      <ModelTable
        ui={${n.ui}}
        app={app}
        rows={rows}
        emptyAction={newButton}
        onOpen={(row) => navigate({ to: ${JSON.stringify(join(page.route, "$id"))}, params: { id: String(row.id) } })}
      />
    </>
  );
}
`;
}

function newRoute(page: PageIR, model: ModelIR, t: Texts): string {
  const n = names(model, t);
  const component = `New${model.name}Page`;
  return `${HEADER}import { createFileRoute, useNavigate } from "@tanstack/react-router";
import { ${n.create}, ${n.schema}, ${n.ui} } from "${n.module}";
import { PageHeader } from "#/kit/AppShell";
import { ModelForm } from "#/kit/ModelForm";

export const Route = createFileRoute(${JSON.stringify(join(page.route, "new"))})({ component: ${component} });

function ${component}() {
  const navigate = useNavigate();
  const back = () => navigate({ to: ${JSON.stringify(page.route)} });
  return (
    <>
      <PageHeader title=${JSON.stringify(`New ${n.label.toLowerCase()}`)} />
      <ModelForm
        ui={${n.ui}}
        schema={${n.schema}}
        submitLabel=${JSON.stringify(`Create ${n.label.toLowerCase()}`)}
        onSubmit={async (values) => {
          await ${n.create}({ data: values });
          await back();
        }}
        onCancel={back}
      />
    </>
  );
}
`;
}

function detailRoute(page: PageIR, model: ModelIR, t: Texts): string {
  const n = names(model, t);
  const component = `${model.name}Page`;
  const title = titleField(model);
  const heading =
    title === "id" ? `\`${n.label} #\${row.id}\`` : `row.${title} || \`${n.label} #\${row.id}\``;
  return `${HEADER}import { createFileRoute, notFound, useNavigate } from "@tanstack/react-router";
import { ${n.remove}, ${n.get}, ${n.schema}, ${n.ui}, ${n.update} } from "${n.module}";
import { PageHeader } from "#/kit/AppShell";
import { ModelForm } from "#/kit/ModelForm";

export const Route = createFileRoute(${JSON.stringify(join(page.route, "$id"))})({
  loader: async ({ params }) => {
    const row = await ${n.get}({ data: Number(params.id) });
    if (!row) throw notFound();
    return row;
  },
  component: ${component},
});

function ${component}() {
  const row = Route.useLoaderData();
  const navigate = useNavigate();
  const back = () => navigate({ to: ${JSON.stringify(page.route)} });
  return (
    <>
      <PageHeader title={${heading}} />
      <ModelForm
        ui={${n.ui}}
        schema={${n.schema}}
        initial={row}
        submitLabel="Save changes"
        onSubmit={async (values) => {
          await ${n.update}({ data: { id: row.id, values } });
          await back();
        }}
        onCancel={back}
        onDelete={async () => {
          await ${n.remove}({ data: row.id });
          await back();
        }}
      />
    </>
  );
}
`;
}

function indexPath(route: string): string {
  return route === "/" ? "/" : `${route}/`;
}

function join(route: string, segment: string): string {
  return route === "/" ? `/${segment}` : `${route}/${segment}`;
}

// ── README ───────────────────────────────────────────────────────────────────

function readme(ir: SpecIR): string {
  return `# ${ir.app.name}
${ir.app.description ? `\n${ir.app.description}\n` : ""}
A [TanStack Start](https://tanstack.com/start) app with [Drizzle](https://orm.drizzle.team) and SQLite, generated by Smithable from \`smithable.yml\`.

## Run it

\`\`\`sh
pnpm install
pnpm db:seed    # optional: sample data
pnpm dev        # http://localhost:3000
\`\`\`

Build and run a container (data is kept in the \`/data\` volume):

\`\`\`sh
docker build -t ${kebab(ir.app.name) || "app"} .
docker run -p 3000:3000 -v ${kebab(ir.app.name) || "app"}-data:/data ${kebab(ir.app.name) || "app"}
\`\`\`

## Project structure

| Path | Owner | What it is |
|---|---|---|
| \`smithable.yml\` | You | What the app does. Smithable regenerates the code from it |
| \`src/generated/\`, \`src/db/schema.ts\`, \`src/db/seed.ts\`, generated routes | Smithable | Regenerated on every change. Files start with a "Generated by Smithable" comment |
| \`src/kit/\`, \`src/components/ui/\` | Smithable | Generic, readable building blocks, updated with Smithable. Copy one into \`src/custom/\` to change it |
| \`src/custom/\` | You | Your own code. Smithable never overwrites it |
| \`drizzle/\` | History | Database migrations. Never rewritten once created |

The app has no dependency on Smithable: it builds and runs with the ordinary tools above.
`;
}

/** A TypeScript literal for plain data, formatted like Biome would. */
function literal(value: unknown, indent = ""): string {
  if (Array.isArray(value)) {
    const inline = `[${value.map((v) => literal(v)).join(", ")}]`;
    if (inline.length <= 80 && !inline.includes("\n")) return inline;
    const inner = `${indent}  `;
    return `[\n${value.map((v) => `${inner}${literal(v, inner)},`).join("\n")}\n${indent}]`;
  }
  if (value !== null && typeof value === "object") {
    const entries = Object.entries(value).filter(([, v]) => v !== undefined);
    const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
    const inline = `{ ${entries.map(([k, v]) => `${key(k)}: ${literal(v)}`).join(", ")} }`;
    if (inline.length <= 80 && !inline.includes("\n")) return inline;
    const inner = `${indent}  `;
    return `{\n${entries.map(([k, v]) => `${inner}${key(k)}: ${literal(v, inner)},`).join("\n")}\n${indent}}`;
  }
  return JSON.stringify(value);
}
