/** A TypeScript literal for plain data, formatted like Biome would. */
function literal(value: unknown, indent = ""): string {
  if (Array.isArray(value)) {
    const inline = `[${value.map((v) => literal(v)).join(", ")}]`;
    if (inline.length <= 80 && !inline.includes("\n")) return inline;
    const inner = `${indent}  `;
    return `[\n${value.map((v) => `${inner}${literal(v, inner)},`).join("\n")}\n${indent}]`;
  }
  if (value !== null && typeof value === "object") {
    const entries = Object.entries(value).filter(([, v]) => v !== undefined);
    const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
    const inline = `{ ${entries.map(([k, v]) => `${key(k)}: ${literal(v)}`).join(", ")} }`;
    if (inline.length <= 80 && !inline.includes("\n")) return inline;
    const inner = `${indent}  `;
    return `{\n${entries.map(([k, v]) => `${inner}${key(k)}: ${literal(v, inner)},`).join("\n")}\n${indent}}`;
  }
  return JSON.stringify(value);
}
