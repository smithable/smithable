import { type SpecIR, validateSpec } from "@smithable/core";
import { describe, expect, test } from "vitest";
import { generateApp } from "./generate.js";

const examples = import.meta.glob("../../../examples/*/smithable.yml", {
  query: "?raw",
  import: "default",
  eager: true,
});

function ir(path: string, text: string): SpecIR {
  const result = validateSpec({ path, text });
  if (!result.ir) throw new Error(`${path} is invalid`);
  return result.ir;
}

const options = { smithableVersion: "0.0.0" };

describe.each(Object.entries(examples))("%s", (path, text) => {
  const files = generateApp(ir(path, text), options);

  test("generation is deterministic: the same spec gives byte-identical files", () => {
    expect(generateApp(ir(path, text), options)).toEqual(files);
  });

  test("the app does not depend on Smithable", () => {
    const pkg = files.find((f) => f.path === "package.json")?.content ?? "";
    expect(pkg).not.toMatch(/smithable/i);
    for (const file of files.filter((f) => /\.(ts|tsx)$/.test(f.path))) {
      expect(file.content, file.path).not.toMatch(/from "@smithable/);
    }
  });

  test("generated files carry the Smithable header", () => {
    for (const file of files.filter((f) => f.zone === "generated" && /\.(ts|tsx)$/.test(f.path))) {
      expect(file.content.startsWith("// Generated by Smithable"), file.path).toBe(true);
    }
  });

  test("file list and generated code", () => {
    expect(files.map((f) => `${f.zone}: ${f.path}`)).toMatchSnapshot();
    for (const file of files.filter((f) => f.zone === "generated")) {
      expect(file.content).toMatchSnapshot(file.path);
    }
  });
});
