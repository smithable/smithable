import { type AuthIR, type SpecIR, validateAuth, validateSpec } from "@smithable/core";
import { describe, expect, test } from "vitest";
import { customPageFromEdit, customPageSource, generateApp } from "./generate.js";

const examples = import.meta.glob("../../../examples/*/smithable.yml", {
  query: "?raw",
  import: "default",
  eager: true,
});
const authFiles = import.meta.glob("../../../examples/*/smithable.auth.yml", {
  query: "?raw",
  import: "default",
  eager: true,
}) as Record<string, string>;

function ir(path: string, text: string): SpecIR {
  const result = validateSpec({ path, text });
  if (!result.ir) throw new Error(`${path} is invalid`);
  return result.ir;
}

function authOf(text: string): AuthIR {
  const result = validateAuth({ path: "smithable.auth.yml", text });
  if (!result.auth) throw new Error("invalid auth file");
  return result.auth;
}

const noSignIn = authOf(
  "smithableAuth: 0.1\nsignIn: none\npublic: { pages: [customers], read: [Customer] }\n",
);
const options = { smithableVersion: "0.0.0", auth: noSignIn };

describe.each(Object.entries(examples))("%s", (path, text) => {
  const auth = authOf(authFiles[path.replace("smithable.yml", "smithable.auth.yml")] as string);
  const files = generateApp(ir(path, text), { ...options, auth });

  test("generation is deterministic: the same spec gives byte-identical files", () => {
    expect(generateApp(ir(path, text), { ...options, auth })).toEqual(files);
  });

  // The guard for refactoring the generator (C7): every file's hash, so a change to the output
  // is always a reviewed snapshot update (`vitest -u`), never a side effect.
  test("the generated files are as reviewed", () => {
    expect(
      Object.fromEntries(files.map((f) => [f.path, `${hash(f.content)} ${f.zone}`])),
    ).toMatchSnapshot();
  });

  test("the app does not depend on Smithable", () => {
    const pkg = files.find((f) => f.path === "package.json")?.content ?? "";
    expect(pkg).not.toMatch(/smithable/i);
    for (const file of files.filter((f) => /\.(ts|tsx)$/.test(f.path))) {
      expect(file.content, file.path).not.toMatch(/from "@smithable/);
    }
  });

  test("generated files carry the Smithable header", () => {
    for (const file of files.filter((f) => f.zone === "generated" && /\.(ts|tsx)$/.test(f.path))) {
      expect(file.content.startsWith("// Generated by Smithable"), file.path).toBe(true);
    }
  });

  test("file list and generated code", () => {
    expect(files.map((f) => `${f.zone}: ${f.path}`)).toMatchSnapshot();
    for (const file of files.filter((f) => f.zone === "generated")) {
      expect(file.content).toMatchSnapshot(file.path);
    }
  });
});

test("visible text comes from smithable.content.yml when given, never from semantic text", () => {
  const spec = ir(
    "smithable.yml",
    `smithable: 0.1
app: { name: CRM }
models:
  Customer:
    fields:
      name: { type: string!, description: Semantic text for AI; not shown. }
      segment: smb | enterprise
pages:
  customers: { crud: Customer }
`,
  );
  const withoutContent = generateApp(spec, options);
  const customer = (files: typeof withoutContent) =>
    files.find((f) => f.path === "src/generated/customer.ts")?.content ?? "";
  expect(customer(withoutContent)).not.toContain("Semantic text");
  expect(customer(withoutContent)).toContain('label: "Smb"');

  const withContent = generateApp(spec, {
    ...options,
    content: {
      models: {
        Customer: {
          label: "Client",
          fields: {
            name: { help: "As on the invoice." },
            segment: { values: { smb: "Small business" } },
          },
        },
      },
      pages: { customers: { title: "Our clients" } },
      menus: {},
    },
  });
  expect(customer(withContent)).toContain('help: "As on the invoice."');
  expect(customer(withContent)).toContain('label: "Small business"');
  expect(customer(withContent)).toContain('pluralLabel: "Clients"');
  const list = withContent.find((f) => f.path === "src/routes/customers/index.tsx")?.content ?? "";
  expect(list).toContain('title="Our clients"');
  expect(list).toContain("New client");
  // A text with quotes goes in braces: a JSX attribute string cannot escape them.
  const quoted = generateApp(spec, {
    ...options,
    content: { models: {}, pages: { customers: { title: 'Our "best" clients' } }, menus: {} },
  });
  expect(quoted.find((f) => f.path === "src/routes/customers/index.tsx")?.content).toContain(
    'title={"Our \\"best\\" clients"}',
  );
});

test("an app without sign-in has no auth library, sign-in page or owners", () => {
  const spec = ir(
    "smithable.yml",
    "smithable: 0.1\napp: { name: Board }\nmodels:\n  Customer: { fields: { name: string! } }\npages:\n  customers: { crud: Customer }\n",
  );
  const files = generateApp(spec, options);
  const paths = files.map((f) => f.path);
  expect(files.find((f) => f.path === "package.json")?.content).not.toContain("better-auth");
  expect(paths).not.toContain("src/routes/sign-in.tsx");
  expect(paths).not.toContain("src/lib/auth-client.ts");
  expect(files.find((f) => f.path === "src/db/schema.ts")?.content).not.toContain("ownerId");
});

test("a required owner gets a user in the access tests, also for a visitor", () => {
  const spec = ir(
    "smithable.yml",
    "smithable: 0.1\napp: { name: Tools }\nmodels:\n  Tool:\n    fields: { name: string!, lender: User! }\n    ownedBy: lender\npages:\n  tools: { crud: Tool }\n",
  );
  const crmAuth = Object.entries(authFiles).find(([path]) => path.includes("/crm/"))?.[1] ?? "";
  const files = generateApp(spec, { ...options, auth: authOf(crmAuth) });
  const test = files.find((f) => f.path === "src/generated/access.test.ts")?.content ?? "";
  expect(test).toContain("lenderId: owner ?? stranger.id");
});

describe("custom pages", () => {
  const path = "../../../examples/crm/smithable.yml";
  const spec = ir(path, examples[path] as string);
  const auth = authOf(authFiles["../../../examples/crm/smithable.auth.yml"] as string);
  const route = (customPages: string[]) =>
    generateApp(spec, { ...options, auth, customPages }).find(
      (f) => f.path === "src/routes/customers/index.tsx",
    )?.content ?? "";

  test("a custom page starts as the generated component, reading the route's data with getRouteApi", () => {
    const source = customPageSource(spec, "customers", { ...options, auth });
    expect(source).toContain('const route = getRouteApi("/customers/");');
    expect(source).toContain("export function CustomersPage() {");
    expect(source).toContain("route.useLoaderData()");
    expect(source).not.toContain("createFileRoute");
    // The component's code is the generated one, with Route replaced by route.
    const generated = route([]);
    expect(source.slice(source.indexOf("export function") + 7)).toBe(
      generated
        .slice(generated.indexOf("function CustomersPage"))
        .replace(/\bRoute\.use/g, "route.use"),
    );
  });

  test("with a custom page, the generated route keeps loading, search and access, and renders it", () => {
    const custom = route(["customers"]);
    expect(custom).toContain('import { CustomersPage } from "#/custom/pages/customers";');
    expect(custom).toContain("guardPage(pageAccess");
    expect(custom).toContain("const searchCustomers = createServerFn()");
    expect(custom).not.toContain("function CustomersPage");
  });

  test("a hand edit of the component moves into the custom page; an edit of the route does not", () => {
    const generated = route([]);
    const edited = generated.replace(
      "  const navigate = useNavigate();",
      "  const navigate = useNavigate();\n  const total = rows.length;",
    );
    const moved = customPageFromEdit(spec, "customers", { ...options, auth }, edited);
    expect(moved.ok && moved.source).toContain("const total = rows.length;");
    expect(moved.ok && moved.source).not.toMatch(
      /customerData|pageAccess|createFileRoute|searchCustomers/,
    );
    const routeEdit = generated.replace("z.string().max(200)", "z.string().max(50)");
    expect(customPageFromEdit(spec, "customers", { ...options, auth }, routeEdit).ok).toBe(false);
  });
});

test("an action checks that the viewer may read every record its input names", () => {
  const crm = Object.entries(examples).find(([path]) => path.includes("/crm/"));
  const auth = Object.entries(authFiles).find(([path]) => path.includes("/crm/"));
  if (!crm || !auth) throw new Error("no CRM");
  const files = generateApp(ir(crm[0], crm[1] as string), {
    ...options,
    auth: authOf(auth[1] as string),
  });
  const action = files.find((f) => f.path === "src/generated/actions/merge-customers.ts")?.content;
  expect(action).toContain("customerData.canRead(viewer, data.keep)");
  expect(action).toContain("customerData.canRead(viewer, data.duplicate)");
  expect(action).toContain("return run(data, viewer);");
});

/** FNV-1a over the text: enough to notice any change, and runs anywhere. */
function hash(text: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) h = Math.imul(h ^ text.charCodeAt(i), 0x01000193);
  return (h >>> 0).toString(16).padStart(8, "0");
}

test("every app carries the third-party notices, in its image too, and no Smithable code under Smithable's licence", () => {
  const ir = validateSpec({ path: "smithable.yml", text: "smithable: 0.1\napp: { name: A }\n" })
    .ir as SpecIR;
  const files = generateApp(ir, { ...options });
  const notice = files.find((f) => f.path === "LICENSES/shadcn-ui.txt")?.content ?? "";
  expect(notice).toContain("MIT License");
  expect(notice).toContain("Copyright (c) 2023 shadcn");
  expect(files.find((f) => f.path === "Dockerfile")?.content).toContain(
    "COPY --from=build /app/LICENSES ./LICENSES",
  );
  expect(files.find((f) => f.path === "README.md")?.content).toContain("## Licences");
  // Nothing in an app is Apache-licensed engine code: no file imports a Smithable package.
  for (const file of files) expect(file.content, file.path).not.toMatch(/@smithable\//);
});
