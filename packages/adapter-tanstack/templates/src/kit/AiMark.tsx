/**
 * The picture, marked when an AI made it; `full` for one across the page, `tiny` for a thumbnail
 * or an avatar of a few rem, where the mark sits in the very corner.
 */
export function AiMarked({
  generated,
  kind,
  full,
  tiny,
  className,
  children,
}: {
  generated?: boolean | undefined;
  kind?: PictureKind | undefined;
  full?: boolean;
  tiny?: boolean;
  className?: string;
  children: ReactNode;
}) {
  if (!generated) return children;
  return (
    <span className={cn("relative block", className)}>
      {children}
      {full ? (
        <span
          data-part="ai-mark"
          data-kind={kind}
          className="pointer-events-none absolute right-2 bottom-2 z-10 flex"
        >
          {language().startsWith("en") ? (
            <AiLabel className="h-5" label={w.aiGenerated} />
          ) : (
            // The EU's set has the worded label in English alone: elsewhere the icon carries the
            // app's own words, joined to it on one black surface as one badge.
            <span className="flex items-center gap-1 rounded-full bg-black pr-2 text-xs font-medium whitespace-nowrap text-white">
              <AiIcon className="size-5" />
              {w.aiGenerated}
            </span>
          )}
        </span>
      ) : (
        <span
          data-part="ai-mark"
          data-kind={kind}
          className={cn(
            "pointer-events-none absolute z-10 flex",
            tiny ? "right-0.5 bottom-0.5" : "right-2 bottom-2",
          )}
        >
          <AiIcon className={tiny ? "size-4" : "size-6"} label={w.aiGenerated} />
        </span>
      )}
    </span>
  );
}
